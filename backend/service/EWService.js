const path = require("path");
const fs = require("fs/promises");
const { randomUUID } = require("crypto");
const Renderer = require("./MapRenderer");
const { copyrightText } = require("../constants");

module.exports = Renderer.withPage("ew", "ewPage", async (page, warning) => {
    await page.evaluate((warning, copyright) => {
        drawEW(warning);
        setFooter(`Generated by Shiny-Map @ ${new Date().toISOString()} / ${copyright} / Data Source: 気象庁`);
    }, warning, copyrightText);
    await Renderer.waitForReady(page);
    const outputPath = path.resolve(process.cwd(), "output", "ew_" + randomUUID() + ".png");
    await fs.mkdir(path.dirname(outputPath), { recursive: true });
    await page.screenshot({ path: outputPath });
    return outputPath;
});
