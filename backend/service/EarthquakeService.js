const path = require("path");
const fs = require("fs/promises");
const { randomUUID } = require("crypto");
const Renderer = require("./MapRenderer");
const { copyrightText } = require("../constants");

module.exports = Renderer.withPage("earthquake", "earthquakePage", async (page, earthquake) => {
    await page.evaluate((earthquake, copyright) => {
        drawEarthquake(earthquake);
        const source = earthquake.source ? " / Data Source: " + earthquake.source : "";
        setFooter(`Generated by Shiny-Map @ ${new Date().toISOString()} / ${copyright}${source}`);
    }, earthquake, copyrightText);
    await Renderer.waitForReady(page);
    const outputPath = path.resolve(process.cwd(), "output", "earthquake_" + randomUUID() + ".png");
    await fs.mkdir(path.dirname(outputPath), { recursive: true });
    await page.screenshot({ path: outputPath });
    return outputPath;
});
